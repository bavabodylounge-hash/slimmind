// ═══════════════════════════════════════════════════════════════
// BC_CODE 연산 함수 (PRD Rule Engine Logic)
// 입력: axisScores (A01~A10 정규화 점수)
// 출력: { bcCode, top1, top2, bcMaster, combinedCode }
// ═══════════════════════════════════════════════════════════════
function computeBCCode(axisScores) {
  // 1. 8대 원인축만 추출 (A09, A10 제외)
  const eightAxes = ['A01','A02','A03','A04','A05','A06','A07','A08'];
  
  const axisArr = eightAxes
    .map(ax => ({ axis: ax, score: axisScores[ax] || 0 }))
    .sort((a, b) => b.score - a.score);
  
  const top1 = axisArr[0]; // 1위
  const top2 = axisArr[1]; // 2위
  
  const bc1Num = AXIS_TO_BC[top1.axis]; // 십의 자리
  const bc2Num = AXIS_TO_BC[top2.axis]; // 일의 자리 (조건부)
  
  const THRESHOLD = 65; // 임계점수
  
  let bcCode;
  let isCombo = false;
  
  if (top2.score >= THRESHOLD) {
    // 조합 코드: BC-61 형태
    bcCode = `BC-${bc1Num}${bc2Num}`;
    isCombo = true;
  } else {
    // 단일 코드: BC-60 형태 (일의 자리 0)
    bcCode = `BC-${bc1Num}0`;
    isCombo = false;
  }
  
  const primaryBCKey = `BC-${bc1Num}`;
  const bcMaster = BC_MASTER[primaryBCKey] || BC_MASTER['BC-6'];
  
  return {
    bcCode,        // 예: "BC-61" 또는 "BC-60"
    primaryBC: primaryBCKey, // 예: "BC-6"
    top1: { ...top1, bcNum: bc1Num },
    top2: { ...top2, bcNum: bc2Num },
    isCombo,
    bcMaster,
    axisRanking: axisArr, // 전체 8축 순위
  };
}

