function compileFinalResult(surveyResult, answers) {
  const { axisScores, ohaengType, axisRanking } = surveyResult;
  
  // BC 코드 연산
  const bcResult = computeBCCode(axisScores);
  
  // 11축 First Domino
  const { firstDomino, axis11Scores } = computeFirstDomino(axisScores);
  
  // 선천 기질 데이터
  const mbtiType = answers['Q_MBTI'] || answers['Q45'] || 'INFP';
  const bloodType = answers['Q_BLOOD'] || answers['Q_BLOODTYPE'] || answers['blood_type'] || 'A';
  const sajuElement = ohaengType || '목';
  const userName = answers['Q01'] || answers['name'] || '회원';
  
  // 오행·MBTI·혈액형 설명
  const ohaengInfo = OHAENG_DESC[sajuElement] || OHAENG_DESC['목'];
  const mbtiInfo = MBTI_DESC[mbtiType] || MBTI_DESC['INFP'];
  const bloodInfo = BLOOD_TYPE_DESC[bloodType] || BLOOD_TYPE_DESC['A'];
  
  // 최종 복합 코드: BC-61-木-INFP-A 형태
  const fullCode = `${bcResult.bcCode}-${sajuElement}-${mbtiType}-${bloodType}형`;
  
  return {
    // 사용자 기본
    userName,
    
    // PAGE 1
    bcCode: bcResult.bcCode,
    primaryBC: bcResult.primaryBC,
    bcMaster: bcResult.bcMaster,
    appNickname: bcResult.bcMaster.appNickname,
    medicalTitle: bcResult.bcMaster.medicalTitle,
    failedTypeDesc: bcResult.bcMaster.failedTypeDesc,
    fullCode,
    
    // PAGE 2
    axis11Scores,
    firstDomino,
    axisScores,
    
    // PAGE 3
    sajuElement,
    ohaengInfo,
    mbtiType,
    mbtiInfo,
    bloodType,
    bloodInfo,
    
    // PAGE 4
    roadmapWeeks: ROADMAP_WEEKS,
    bcResult,
  };
}

