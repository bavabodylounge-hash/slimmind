// 11축 점수 → First Domino 연산
// ═══════════════════════════════════════════════════════════════
function computeFirstDomino(axisScores) {
  // 11축 각각의 점수 계산 (axisKey로 survey 점수 매핑)
  const axis11Scores = AXIS_11_META.map(meta => {
    const score = axisScores[meta.axisKey] || 0;
    return { ...meta, score };
  });
  
  // 1위 = First Domino
  axis11Scores.sort((a, b) => b.score - a.score);
  const firstDomino = axis11Scores[0];
  
  return {
    firstDomino,
    axis11Scores,
  };
}

