// 3. BC_CODE 연산 함수
// ──────────────────────────────────────────────
function computeBCCode(axisScores) {
  // axisScores: { A01:숫자, A02:숫자, ..., A10:숫자 } (0~100 정규화)

  // 8대 원인축 점수 산출 (PRD: 약·식·복·확·한·심·형·관)
  const causalScores = {};

  // 약: A08 기반
  causalScores['약'] = axisScores['A08'] || 0;
  // 식: A01 + A05 평균
  causalScores['식'] = Math.round(((axisScores['A01'] || 0) + (axisScores['A05'] || 0)) / 2);
  // 복: A07
  causalScores['복'] = axisScores['A07'] || 0;
  // 확: A03 (호르몬·대사)
  causalScores['확'] = axisScores['A03'] || 0;
  // 한: A02 + A05 평균
  causalScores['한'] = Math.round(((axisScores['A02'] || 0) + (axisScores['A05'] || 0)) / 2);
  // 심: A08 (심리·식이행동) — 약과 동일 원천이나 독립 축으로 취급
  //     실제 구분: 약=A08 약물의존도, 심=A08 심리폭식 → 약은 A09도 가중
  causalScores['심'] = Math.round(((axisScores['A08'] || 0) + (axisScores['A07'] || 0)) / 2);
  // 형: A06
  causalScores['형'] = axisScores['A06'] || 0;
  // 관: A02 + A04 평균
  causalScores['관'] = Math.round(((axisScores['A02'] || 0) + (axisScores['A04'] || 0)) / 2);

  // 정렬 (내림차순)
  const sorted = Object.entries(causalScores).sort((a, b) => b[1] - a[1]);
  const top1 = sorted[0]; // [축명, 점수]
  const top2 = sorted[1]; // [축명, 점수]

  // BC 번호 결정
  const bc1Num = CAUSAL_AXIS_META[top1[0]].bcNum;
  const bc2Num = CAUSAL_AXIS_META[top2[0]].bcNum;

  let bcCode;
  const THRESHOLD = 65;

  if (top2[1] >= THRESHOLD) {
    // 조합 코드: BC-{십의자리}{일의자리}
    bcCode = `BC-${bc1Num}${bc2Num}`;
  } else {
    // 단일 코드: BC-{번호}0
    bcCode = `BC-${bc1Num}0`;
  }

  // BC 마스터 찾기 (단순화: Top-1 BC 번호 기준)
  const masterKey = `BC-${bc1Num}`;
  const bcMaster = BC_MASTER[masterKey] || BC_MASTER['BC-6'];

  // 11대 축 점수 (PAGE 2용)
  const axis11Scores = {};
  AXIS_11.forEach(ax => {
    axis11Scores[ax.key] = axisScores[ax.axisRef] || 0;
  });

  // 첫 번째 도미노 = Top-1 축 라벨
  const firstDomino = CAUSAL_AXIS_META[top1[0]].label;

  return {
    bcCode,          // 'BC-61' 등 조합코드
    masterKey,       // 'BC-6' 마스터 키
    bcMaster,        // BC 마스터 객체
    causalScores,    // 8대 원인축 점수
    sorted,          // 정렬된 원인축 배열
    top1, top2,
    firstDomino,
    axis11Scores,
  };
}

